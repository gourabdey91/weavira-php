  /* ══════════════════════════════════════════════════════════════════════════
     CART PAGE — quantity, remove, and "This will be a Gift" per line item.
     Every request is scoped to one cart_item_key, so gift details (and
     quantity/removal) only ever affect the specific line they're on.
     ══════════════════════════════════════════════════════════════════════════ */
  (function () {
    var cartItemsEl = document.querySelector('.cart-items');
    if (!cartItemsEl) return;

    /* Reuses the same #wv-cart-toast element other pages use for
       "added to bag" — here only ever shown in its error styling, for
       out-of-stock/quantity-capped feedback from the AJAX handler. */
    var stockToast = document.getElementById('wv-cart-toast');
    var stockToastTitle = document.getElementById('wv-cart-toast-title');
    var stockToastTimer = null;

    function showStockToast(message) {
      if (!stockToast) return;
      stockToast.classList.add('wv-cart-toast--error');
      if (stockToastTitle) { stockToastTitle.textContent = message; }
      stockToast.hidden = false;
      void stockToast.offsetWidth;
      stockToast.classList.add('wv-cart-toast--visible');
      clearTimeout(stockToastTimer);
      stockToastTimer = setTimeout(function () {
        stockToast.classList.remove('wv-cart-toast--visible');
      }, 4000);
    }

    // Counts cart mutations still in flight (qty, remove, gift save — they
    // all come through here) so the checkout link below can wait for the
    // server-side cart to actually catch up before navigating.
    var inFlight = 0;

    function cartAjax(action, params) {
      var body = new URLSearchParams(Object.assign({
        action: action,
        security: ajax_object.cart_nonce,
      }, params));

      inFlight++;

      return fetch(ajax_object.ajaxurl, {
        method: 'POST',
        credentials: 'same-origin',
        headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
        body: body.toString(),
      })
        .then(function (res) { return res.json(); })
        .then(function (json) { inFlight--; return json; })
        .catch(function (err) { inFlight--; throw err; });
    }

    function applyTotals(data) {
      if (!data) return;

      var subtotalEl = document.querySelector('.cart-summary-subtotal');
      var shippingEl = document.querySelector('.cart-summary-shipping');
      var taxesEl    = document.querySelector('.cart-summary-taxes');
      var totalEl    = document.querySelector('.cart-summary-total-price');
      var badge      = document.querySelector('.wv-cart-badge');

      if (subtotalEl && data.subtotal !== undefined) { subtotalEl.innerHTML = data.subtotal; }
      if (totalEl && data.total !== undefined) { totalEl.innerHTML = data.total; }

      if (shippingEl && data.shippingLabel !== undefined) {
        shippingEl.textContent = data.shippingLabel || 'Calculated at checkout';
        shippingEl.classList.toggle('cart-summary-free', !!data.isFreeShipping);
      }

      if (taxesEl && data.taxRows) {
        taxesEl.innerHTML = data.taxRows.map(function (tax) {
          return '<div class="cart-summary-row"><span>' + tax.label + ' (Included)</span><span>' + tax.amount + '</span></div>';
        }).join('');
      }

      if (badge && data.cartCount !== undefined) {
        badge.textContent = data.cartCount;
        badge.hidden = data.cartCount < 1;
        badge.setAttribute('aria-label', data.cartCount + ' item' + (data.cartCount === 1 ? '' : 's'));
      }

      if (data.isEmpty) {
        window.location.reload();
      }
    }

    /* ── Quantity +/- ──
       Debounced so holding down +/- doesn't fire a request per click. The
       deferred work is kept in qtyPending so the checkout link below can
       run it early rather than let the customer navigate away with the
       new quantity never having reached the server. */
    var qtyTimers = {};
    var qtyPending = {};

    cartItemsEl.addEventListener('click', function (e) {
      var btn = e.target.closest('.cart-qty-btn');
      if (!btn) return;

      var itemEl = btn.closest('.cart-item');
      var key = itemEl.getAttribute('data-cart-item-key');
      var valEl = itemEl.querySelector('.cart-qty-val');
      var current = parseInt(valEl.textContent, 10) || 1;
      var next = btn.getAttribute('aria-label') === 'Increase quantity' ? current + 1 : current - 1;

      if (next < 1) { next = 1; } // Remove button handles going to zero explicitly.

      valEl.textContent = next;

      var run = function () {
        delete qtyPending[key];

        cartAjax('weavira_update_cart_item', { cart_item_key: key, quantity: next }).then(function (json) {
          if (!json || !json.success) return;
          applyTotals(json.data);
          // .cart-item-unit-price holds the line total (unit x qty) — see
          // cart.blade.php; .cart-item-price is the fixed per-unit rate,
          // which never changes with quantity.
          var priceEl = itemEl.querySelector('.cart-item-unit-price');
          if (priceEl && json.data.lineTotal) { priceEl.innerHTML = '<span class="cart-item-total-label">Total:</span> ' + json.data.lineTotal; }

          if (json.data.stockMessage) {
            valEl.textContent = json.data.quantity;
            showStockToast(json.data.stockMessage);
          }
        });
      };

      clearTimeout(qtyTimers[key]);
      qtyPending[key] = run;
      qtyTimers[key] = setTimeout(run, 400);
    });

    /* ── Checkout link: wait for the cart to actually catch up ──
       "Proceed to Secure Checkout" is a plain link, so without this a
       customer who bumps quantity and immediately clicks it navigates
       away before the debounced update is even sent — checkout would then
       show the old quantity. Only intercepts when something is genuinely
       outstanding, so the usual case stays instant. */
    (function () {
      var checkoutBtn = document.querySelector('.cart-checkout-btn');
      if (!checkoutBtn) return;

      function hasPendingWork() {
        return inFlight > 0 || Object.keys(qtyPending).length > 0;
      }

      checkoutBtn.addEventListener('click', function (e) {
        if (!hasPendingWork()) return;

        e.preventDefault();
        checkoutBtn.classList.add('is-busy');

        Object.keys(qtyPending).forEach(function (key) {
          clearTimeout(qtyTimers[key]);
          qtyPending[key]();
        });

        var waited = 0;

        var poll = setInterval(function () {
          waited += 60;

          // Ceiling so a hung or failed request can't strand the customer
          // here — checkout re-reads the real server-side cart anyway.
          if (!hasPendingWork() || waited >= 5000) {
            clearInterval(poll);
            window.location.href = checkoutBtn.href;
          }
        }, 60);
      });
    }());

    /* ── Remove ── */
    cartItemsEl.addEventListener('click', function (e) {
      var btn = e.target.closest('.cart-remove-btn');
      if (!btn) return;

      var itemEl = btn.closest('.cart-item');
      var key = itemEl.getAttribute('data-cart-item-key');

      itemEl.style.opacity = '0.5';
      itemEl.style.pointerEvents = 'none';

      cartAjax('weavira_remove_cart_item', { cart_item_key: key }).then(function (json) {
        if (!json || !json.success) { itemEl.style.opacity = ''; itemEl.style.pointerEvents = ''; return; }
        applyTotals(json.data);
        itemEl.remove();
      });
    });

  }());

