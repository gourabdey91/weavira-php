  /* ── Hero Banner Slider (auto-advance, cross-dissolve, no arrows) ───── */
  (function () {
    var track = document.getElementById('hero-slider-track');
    if (!track) return;

    var slides  = track.querySelectorAll('.hero-slide');
    var total   = slides.length;
    var current = 0;
    var timer;

    function goTo(idx) {
      var next = (idx + total) % total;
      var out  = slides[current];
      out.classList.remove('active');
      out.classList.add('leaving');
      setTimeout(function () { out.classList.remove('leaving'); }, 1170);
      current = next;
      slides[current].classList.add('active');
    }

    function startTimer() {
      timer = setInterval(function () { goTo(current + 1); }, 9000);
    }

    startTimer();
  })();

  /* ── Carousel helper: scroll-driven dots (dots generated by JS) ─────
     trackId   : id of the scrollable track element
     dotClass  : CSS class for each dot button
     dotsWrap  : container element that will receive generated dots        */
  function initCarousel(trackId, dotClass, dotsWrapSelector) {
    var track = document.getElementById(trackId);
    var wrap  = dotsWrapSelector ? document.querySelector(dotsWrapSelector) : null;
    if (!track) return;

    /* Build dots dynamically from item count */
    var items = track.children;
    if (wrap && items.length > 1) {
      wrap.innerHTML = '';
      var numDots = Math.min(items.length, 8);
      for (var i = 0; i < numDots; i++) {
        var btn = document.createElement('button');
        btn.className = dotClass + (i === 0 ? ' active' : '');
        btn.setAttribute('aria-label', 'Go to item ' + (i + 1));
        wrap.appendChild(btn);
      }
    }

    var dots = wrap ? wrap.querySelectorAll('.' + dotClass) : [];

    function updateDots() {
      if (!dots.length) return;
      var max = track.scrollWidth - track.clientWidth;
      if (max <= 0) return;
      var idx = Math.min(
        Math.round((track.scrollLeft / max) * (dots.length - 1)),
        dots.length - 1
      );
      dots.forEach(function (d, i) { d.classList.toggle('active', i === idx); });
    }

    track.addEventListener('scroll', updateDots);

    dots.forEach(function (dot, i) {
      dot.addEventListener('click', function () {
        var max = track.scrollWidth - track.clientWidth;
        track.scrollTo({ left: (i / (dots.length - 1)) * max, behavior: 'smooth' });
      });
    });
  }

