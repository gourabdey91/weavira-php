  /* ── PDP: Gallery thumbnails + auto-slider ────────────────────────── */
  var galleryMain = document.querySelector('.gallery-main');
  if (galleryMain) {
    var pdpThumbs   = Array.from(document.querySelectorAll('.gallery-thumb'));
    var mainPhoto   = document.querySelector('.gallery-main-photo');
    var mainVideo   = document.querySelector('.gallery-main-video');
    var slideTimer  = null;
    var SLIDE_MS    = 5000;

    var slideCounter = document.querySelector('.gallery-slide-counter');
    var total = pdpThumbs.length;
    if (slideCounter) { slideCounter.textContent = '1 / ' + total; }

    function activateSlide(index) {
      pdpThumbs.forEach(function (t) { t.classList.remove('active'); });
      pdpThumbs[index].classList.add('active');

      var thumb = pdpThumbs[index];
      var videoSrc = thumb.getAttribute('data-video-src');
      var img = thumb.querySelector('.gallery-thumb-img');

      if (videoSrc && mainVideo) {
        if (mainVideo.getAttribute('src') !== videoSrc) { mainVideo.src = videoSrc; }
        if (img) { mainVideo.poster = img.src; }
        mainVideo.hidden = false;
        if (mainPhoto) { mainPhoto.style.display = 'none'; }
        stopSlide();

        mainVideo.muted = false;
        var playAttempt = mainVideo.play();
        if (playAttempt && typeof playAttempt.catch === 'function') {
          playAttempt.catch(function () {
            mainVideo.muted = true;
            mainVideo.play().catch(function () {});
          });
        }
      } else {
        if (mainVideo) { mainVideo.pause(); mainVideo.hidden = true; }
        if (mainPhoto) { mainPhoto.style.display = ''; }
        if (img && mainPhoto) {
          mainPhoto.src = img.src;
          mainPhoto.alt = img.alt || mainPhoto.alt;
        }
      }

      if (slideCounter) { slideCounter.textContent = (index + 1) + ' / ' + total; }
    }

    function nextSlide() {
      var cur = pdpThumbs.findIndex(function (t) { return t.classList.contains('active'); });
      activateSlide((cur + 1) % pdpThumbs.length);
    }

    var isPlaying = true;
    var playToggle = document.querySelector('.gallery-play-toggle');

    function syncPlayToggle() {
      if (!playToggle) return;
      playToggle.classList.toggle('is-paused', !isPlaying);
      playToggle.setAttribute('aria-label', isPlaying ? 'Pause slideshow' : 'Play slideshow');
    }

    function startSlide() {
      if (slideTimer) clearInterval(slideTimer);
      slideTimer = setInterval(nextSlide, SLIDE_MS);
      isPlaying = true;
      syncPlayToggle();
    }

    function stopSlide() {
      if (slideTimer) { clearInterval(slideTimer); slideTimer = null; }
      isPlaying = false;
      syncPlayToggle();
    }

    if (playToggle) {
      playToggle.addEventListener('click', function () {
        if (isPlaying) {
          stopSlide();
        } else {
          startSlide();
        }
      });
    }

    pdpThumbs.forEach(function (thumb, idx) {
      thumb.addEventListener('click', function () {
        activateSlide(idx);
        if (!thumb.getAttribute('data-video-src')) { startSlide(); }
      });
    });

    startSlide();
  }

