  var galleryExpand = document.querySelector('.gallery-expand');
  if (galleryExpand) {
    var lightbox = document.createElement('div');
    lightbox.className = 'gallery-lightbox';
    lightbox.setAttribute('role', 'dialog');
    lightbox.setAttribute('aria-modal', 'true');
    lightbox.setAttribute('aria-label', 'Fullscreen image view');
    lightbox.innerHTML =
      '<button class="gallery-lightbox-close" aria-label="Close fullscreen">' +
        '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" aria-hidden="true"><path d="M18 6L6 18M6 6l12 12"/></svg>' +
      '</button>' +
      '<button class="gallery-lightbox-prev" aria-label="Previous image">' +
        '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" aria-hidden="true"><polyline points="15 18 9 12 15 6"/></svg>' +
      '</button>' +
      '<img class="gallery-lightbox-img" src="" alt="">' +
      '<button class="gallery-lightbox-next" aria-label="Next image">' +
        '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" aria-hidden="true"><polyline points="9 18 15 12 9 6"/></svg>' +
      '</button>' +
      '<div class="gallery-lightbox-dots"></div>';
    document.body.appendChild(lightbox);

    var lbImg        = lightbox.querySelector('.gallery-lightbox-img');
    var lbClose      = lightbox.querySelector('.gallery-lightbox-close');
    var lbPrev       = lightbox.querySelector('.gallery-lightbox-prev');
    var lbNext       = lightbox.querySelector('.gallery-lightbox-next');
    var lbDotsWrap   = lightbox.querySelector('.gallery-lightbox-dots');
    var lbIndex      = 0;
    var lbTimer      = null;
    var lbTouchX     = 0;
    var AUTO_DELAY   = 4000;

    function getThumbs() { return Array.from(document.querySelectorAll('.gallery-thumb')); }

    function buildDots(count) {
      lbDotsWrap.innerHTML = '';
      for (var i = 0; i < count; i++) {
        (function (idx) {
          var dot = document.createElement('span');
          dot.className = 'gallery-lightbox-dot';
          dot.addEventListener('click', function (e) { e.stopPropagation(); navigate(idx - lbIndex); });
          lbDotsWrap.appendChild(dot);
        })(i);
      }
    }

    function updateDots() {
      Array.from(lbDotsWrap.querySelectorAll('.gallery-lightbox-dot')).forEach(function (d, i) {
        d.classList.toggle('active', i === lbIndex);
      });
    }

    function showImage(index) {
      var thumbs = getThumbs();
      if (!thumbs.length) return;
      lbIndex = (index + thumbs.length) % thumbs.length;
      var img = thumbs[lbIndex].querySelector('.gallery-thumb-img');
      if (img) { lbImg.src = img.src; lbImg.alt = img.alt; }
      thumbs.forEach(function (t) { t.classList.remove('active'); });
      thumbs[lbIndex].classList.add('active');
      var mainPhoto = document.querySelector('.gallery-main-photo');
      if (mainPhoto && img) { mainPhoto.src = img.src; mainPhoto.alt = img.alt || mainPhoto.alt; }
      updateDots();
    }

    function startAuto() {
      stopAuto();
      lbTimer = setInterval(function () { showImage(lbIndex + 1); }, AUTO_DELAY);
    }

    function stopAuto() {
      if (lbTimer) { clearInterval(lbTimer); lbTimer = null; }
    }

    function navigate(delta) {
      stopAuto();
      showImage(lbIndex + delta);
      startAuto();
    }

    function openLightbox() {
      var thumbs = getThumbs();
      var activeIndex = 0;
      thumbs.forEach(function (t, i) { if (t.classList.contains('active')) activeIndex = i; });
      buildDots(thumbs.length);
      showImage(activeIndex);
      lightbox.classList.add('open');
      document.body.style.overflow = 'hidden';
      startAuto();
    }

    function closeLightbox() {
      lightbox.classList.remove('open');
      document.body.style.overflow = '';
      stopAuto();
    }

    galleryExpand.addEventListener('click', openLightbox);
    lbClose.addEventListener('click', closeLightbox);
    lbPrev.addEventListener('click', function (e) { e.stopPropagation(); navigate(-1); });
    lbNext.addEventListener('click', function (e) { e.stopPropagation(); navigate(1); });
    lightbox.addEventListener('click', function (e) { if (e.target === lightbox) closeLightbox(); });

    lightbox.addEventListener('touchstart', function (e) {
      lbTouchX = e.touches[0].clientX;
    }, { passive: true });

    lightbox.addEventListener('touchend', function (e) {
      var diff = lbTouchX - e.changedTouches[0].clientX;
      if (Math.abs(diff) > 50) navigate(diff > 0 ? 1 : -1);
    }, { passive: true });

    document.addEventListener('keydown', function (e) {
      if (!lightbox.classList.contains('open')) return;
      if (e.key === 'Escape')     closeLightbox();
      if (e.key === 'ArrowLeft')  navigate(-1);
      if (e.key === 'ArrowRight') navigate(1);
    });
  }

